function setLanguage(lang) {
  const t = translations[lang];
  
  // Save language to localStorage
  localStorage.setItem('gameLanguage', lang);
  
  document.getElementById('title').textContent = t.title;
  document.getElementById('startBtn').textContent = t.startBtn;
  document.getElementById('openRulesModal').textContent = t.rulesBtn;
  document.getElementById('openLangModal').textContent = t.langBtn;
  document.getElementById('rulesTitle').textContent = t.rulesTitle;
  document.getElementById('rulesList').innerHTML = t.rules.map(rule => `<li>${rule}</li>`).join('');
  document.getElementById('closeRulesModal').textContent = t.closeBtn;
  document.getElementById('langTitle').textContent = t.langTitle;
  document.getElementById('closeLangModal').textContent = t.closeBtn;
}

document.getElementById('openRulesModal').addEventListener('click', () => document.getElementById('rulesModal').showModal());
document.getElementById('closeRulesModal').addEventListener('click', () => document.getElementById('rulesModal').close());
document.getElementById('openLangModal').addEventListener('click', () => document.getElementById('langModal').showModal());
document.getElementById('closeLangModal').addEventListener('click', () => document.getElementById('langModal').close());

// Initialize with saved language or Ukrainian
const savedLanguage = localStorage.getItem('gameLanguage') || 'uk';
setLanguage(savedLanguage);